export const SLOTS = Object.freeze(TABLE.map((v) => Object.freeze(v)));

/** The unit vector of slot k; negative and large k wrap around the table. */
export function slot(k) {
  const n = SLOTS.length;
  const i = Number.isInteger(k) ? ((k % n) + n) % n : 0;
  return SLOTS[i];
}

/**
 * n points of a sunflower (phyllotaxis) disc of the given radius, centred on
 * [cx, cy]: point k sits at radius * sqrt((k + 0.5) / n) along slot k. Only
 * + - * / and Math.sqrt, so the disc is identical on every runtime.
 */
export function sunflower(n, radius, cx = 0, cy = 0) {
  const out = [];
  const count = Math.max(0, Math.floor(n));
  for (let k = 0; k < count; k += 1) {
    const r = radius * Math.sqrt((k + 0.5) / count);
    const s = slot(k);
    out.push([cx + r * s[0], cy + r * s[1]]);
  }
  return out;
}
