#!/usr/bin/env node
// Writes references/RULES.md from lib/rules/*.mjs: the pinned counts, the
// exit codes, the gate order and every DF_* code with its repair sentence.
// `--check` exits 1 when the committed file is stale. Output has no dates,
// so two runs over the same catalog produce identical bytes.
import { existsSync, readFileSync, realpathSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { CODES, FAMILIES, PINNED, RULES, RULE_CATALOG_VERSION } from '../lib/rules.mjs';
import { EXIT_CODES, NAMES } from '../lib/exit-codes.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const OUTPUT = join(ROOT, 'references', 'RULES.md');

const EXIT_WHEN = {
  OK: 'the command finished what it was asked to do',
  UNEXPECTED: 'an unexpected error; a receipt with status error is still written',
  GATE: 'a blocking gate failed; the receipt lists every check that ran',
  AWAITING_OWNER: 'stopped at the approval hop, an owner gate, or a not-owner refusal',
  STORAGE: 'a typed storage fault (503); nothing was partially written',
  PROVIDER: 'the provider adapter is unavailable or answered badly',
};

const GATE_ORDER = [
  ['render', 'schema → topology (incl. fields budget) → privacy (HMAC stamp, viewer exclusion, foreign bodies, absolute paths, taint) → layout → render → receipt; the first blocking failure stops with exit 2'],
  ['validate', 'schema → topology → privacy → layout (no render output); room manifests add the room family'],
  ['share project', 'schema → share → receipt'],
  ['run', 'DF_RUN_ROUTE_PARITY, DF_RUN_NO_CHALLENGER, DF_RUN_BUDGET_EXCEEDED, DF_RUN_WRITE_BEFORE_APPROVAL, DF_RUN_FOREIGN_UNFENCED → receipt'],
  ['verify', 'the receipt family over one receipt.json'],
  ['compare', 'load both (an unreadable input is DF_DELTA_INPUT_BLOCKED) → DF_DELTA_KIND_MISMATCH → each input: schema → topology → privacy → layout (DF_DELTA_INPUT_BLOCKED; DF_DELTA_LAID_OUT_COLD, non-blocking, when one is laid out cold) → diff (DF_DELTA_NO_STABLE_IDS, DF_DELTA_EDGE_PAIRED_BY_ENDPOINTS) → the after scene with its delta: schema → topology → privacy → layout, and delta.json against schemas/delta.schema.json → render → receipt'],
];

function esc(s) {
  return String(s).replace(/\|/g, '\\|');
}

export function renderRulesMd() {
  const lines = [];
  const push = (...xs) => lines.push(...xs);
  push('# Rule catalog — `DF_*` codes (generated)', '');
  push(`> Generated by \`node scripts/gen-rules-md.mjs\` from \`lib/rules/*.mjs\` (catalog version ${RULE_CATALOG_VERSION}). Do not edit by hand: \`node scripts/gen-rules-md.mjs --check\` fails when this file is stale and \`npm run rules:md\` regenerates it.`, '');
  push('Every gate, command, route and tool reports the same check shape, `{code, gate, blocking, status, path?, message?, repair?}`, built by `finding()` in `lib/rules.mjs`. A failing check carries the repair sentence below; the skill applies it by code and never edits `lib/`, `schemas/` or `renderers/` to make a gate pass. A code lives in exactly one family file, `lib/rules/<family>.mjs`; a later component adds a code only to its own family. `Exit` is the process exit a *blocking* failure maps to (`lib/exit-codes.mjs fromReceipt()`); the default is 2.', '');
  push('## Pinned counts', '', '| Constant | Value | Held by |', '|---|---|---|');
  push(`| CLI verbs | ${PINNED.cli_verbs} | \`test/cli.test.js\` |`);
  push(`| CLI leaf subverbs | ${PINNED.cli_leaf_subverbs} | \`test/cli.test.js\`, \`test/structure.test.js\` |`);
  push(`| MCP tools | ${PINNED.mcp_tools} | \`test/mcp.test.js\`, \`test/structure.test.js\` |`);
  push(`| Rule families | ${PINNED.rule_families} | \`test/rules.test.js\` |`);
  push(`| Rule codes | ${CODES.length} | \`test/rules.test.js\` |`);
  push(`| three.js revision | ${PINNED.three_revision} | \`test/vendor.test.js\` |`);
  push(`| Minimum Node | ${PINNED.min_node} | \`dotfield doctor\` (\`DF_ENGINE_NODE_VERSION\`) |`);
  push('', '## Exit codes (`lib/exit-codes.mjs`)', '', '| Code | Name | When |', '|---|---|---|');
  for (const [name, code] of Object.entries(EXIT_CODES).sort((a, b) => a[1] - b[1])) push(`| ${code} | \`${NAMES[code]}\` | ${EXIT_WHEN[name]} |`);
  push('', '## Gate order', '', '| Verb | Order |', '|---|---|');
  for (const [verb, order] of GATE_ORDER) push(`| \`${verb}\` | ${esc(order)} |`);
  push('', '## Families', '');
  for (const f of FAMILIES) push(`- [\`${f.id}\`](#family-${f.id}) — gate \`${f.gate}\`, ${f.codes.length} codes`);
  for (const f of FAMILIES) {
    push('', `### Family \`${f.id}\``, '', `Gate \`${f.gate}\` · ${f.codes.length} codes · \`lib/rules/${f.id}.mjs\``, '');
    push('| Code | Blocking | Exit | Message | Repair |', '|---|---|---|---|---|');
    for (const code of f.codes) {
      const r = RULES[code];
      push(`| \`${code}\` | ${r.blocking ? 'yes' : 'no'} | ${r.blocking ? (r.exit ?? EXIT_CODES.GATE) : '—'} | ${esc(r.message)} | ${esc(r.repair)} |`);
    }
  }
  return `${lines.join('\n')}\n`;
}

export function main(argv = process.argv.slice(2)) {
  const text = renderRulesMd();
  if (argv.includes('--check')) {
    const current = existsSync(OUTPUT) ? readFileSync(OUTPUT, 'utf8') : null;
    if (current === text) { process.stdout.write(`references/RULES.md is current (${CODES.length} codes, ${FAMILIES.length} families)\n`); return 0; }
    process.stderr.write('references/RULES.md is stale: run `npm run rules:md` and commit the result\n');
    return 1;
  }
  writeFileSync(OUTPUT, text, 'utf8');
  process.stdout.write(`wrote references/RULES.md (${CODES.length} codes, ${FAMILIES.length} families)\n`);
  return 0;
}

const invokedDirectly = (() => { try { return Boolean(process.argv[1]) && realpathSync(process.argv[1]) === realpathSync(fileURLToPath(import.meta.url)); } catch { return false; } })();
if (invokedDirectly) {
  process.exitCode = main();
}
